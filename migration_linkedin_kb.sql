-- STEP 1: Recreate tables to match new schema
-- WARNING: This drops all existing data!
DROP TABLE IF EXISTS career_skills CASCADE;
DROP TABLE IF EXISTS careers CASCADE;
DROP TABLE IF EXISTS skills CASCADE;
DROP TABLE IF EXISTS education_levels CASCADE;

CREATE TABLE education_levels (
  id SERIAL PRIMARY KEY,
  level_name TEXT NOT NULL,
  order_rank INTEGER NOT NULL
);

CREATE TABLE skills (
  id SERIAL PRIMARY KEY,
  skill_name TEXT NOT NULL,
  category TEXT,
  skill_type TEXT
);

CREATE TABLE careers (
  id SERIAL PRIMARY KEY,
  career_name TEXT NOT NULL,
  career_description TEXT,
  min_education_rank INTEGER NOT NULL DEFAULT 3,
  location_bias TEXT,
  salary_min NUMERIC,
  salary_max NUMERIC
);

CREATE TABLE career_skills (
  id SERIAL PRIMARY KEY,
  career_id INTEGER REFERENCES careers(id),
  skill_id INTEGER REFERENCES skills(id),
  weight_pct NUMERIC,
  is_required BOOLEAN
);

CREATE TABLE IF NOT EXISTS user_journeys (
  id SERIAL PRIMARY KEY,
  user_params JSONB,
  opportunity_overview JSONB,
  journey_timeline JSONB,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

