-- ---------------------------------------------------------------------------
-- Kenapa ketahanan AI dihitung ulang
-- ---------------------------------------------------------------------------
-- 0012 menurunkan ai_resilience dari komposisi Activity DNA. Itu bekerja, tapi
-- Activity DNA cuma 12 atribut hasil peringkasan kita sendiri, jadi hasilnya
-- kasar: Kasir keluar 82 (sangat tahan), padahal pekerjaan kasir termasuk yang
-- paling banyak diotomasi dalam satu dekade terakhir.
--
-- Versi ini memakai bahan yang lebih dekat ke pekerjaannya: 41 Generalized
-- Work Activity O*NET, dibobot dengan Importance tiap Task Statement profesi
-- itu (18.796 task, skala IM 1-5). Untuk tiap GWA diberi skor ketahanan yang
-- ditulis eksplisit di bawah, mengikuti tiga "bottleneck" otomasi yang sampai
-- sekarang bertahan: persepsi dan manipulasi di lingkungan tak terstruktur,
-- kecerdasan kreatif, dan kecerdasan sosial. Yang paling terekspos adalah
-- aktivitas yang mengolah informasi menurut aturan tetap -- Processing
-- Information (20), Documenting/Recording Information (20), Performing
-- Administrative Activities (20). Yang paling bertahan adalah Assisting and
-- Caring for Others (95), Coaching and Developing Others (95), Developing and
-- Building Teams (95).
--
-- Skor mentah lalu diregangkan ke 30..97 supaya seluruh rentang label terpakai,
-- dan digeser menurut Job Zone: pekerjaan yang hampir tidak butuh persiapan
-- lebih mudah digantikan meski isinya berinteraksi dengan orang (JZ1 -12,
-- JZ2 -6, JZ3 0, JZ4 +4, JZ5 +8). Penyesuaian inilah yang menurunkan Kasir
-- dari 55 ke 49 (Rentan) tanpa menyentuh Perawat (74, Tahan).
--
-- Ini tetap estimasi model, bukan survei. source tetap 'estimasi_model'.
--
-- ---------------------------------------------------------------------------
-- Kenapa gaji senioritas diturunkan, bukan didata
-- ---------------------------------------------------------------------------
-- Mendata tiga kisaran gaji untuk 477 profesi berarti 1.431 angka yang tidak
-- bisa diverifikasi. Yang kita punya adalah satu kisaran "wajar" per profesi
-- dari 0012. Tiga tingkat diturunkan darinya dengan bentuk yang sama untuk
-- semua profesi:
--
--   Junior    (0-2 th)  : 0,82 x min      ..  min + 0,25 x rentang
--   Mid-level (3-7 th)  : min + 0,25 x rentang ..  1,10 x maks
--   Senior    (>7 th)   : 1,10 x maks     ..  1,72 x maks
--
-- Bentuk ini dicocokkan ke contoh di desain (kisaran utama Rp 5,5-10,5 juta
-- menghasilkan 4,5-6,8 / 6,8-11,6 / 11,6-18,1 juta; desain menulis 4,5-6,5 /
-- 6,5-11,5 / 11,5-18). Dibulatkan ke ratusan ribu terdekat.
