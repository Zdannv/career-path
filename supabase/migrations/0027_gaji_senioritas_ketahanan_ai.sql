with b as (
  select m.career_id,
         m.salary_min::numeric               as bawah,
         m.salary_max::numeric               as atas,
         (m.salary_max - m.salary_min)::numeric as rentang
  from public.career_market m
  join public.careers c on c.id = m.career_id and c.is_active
  where m.salary_min is not null and m.salary_max is not null
),
r as (
  select career_id, 'JUNIOR' as level_code,
         bawah * 0.82            as lo, bawah + rentang * 0.25 as hi from b
  union all
  select career_id, 'MID',
         bawah + rentang * 0.25,       atas * 1.10             from b
  union all
  select career_id, 'SENIOR',
         atas * 1.10,                  atas * 1.72             from b
)
insert into public.career_salary_bands (career_id, level_code, salary_min, salary_max)
select career_id, level_code,
       (round(lo / 100000) * 100000)::bigint,
       (round(hi / 100000) * 100000)::bigint
from r;

-- ---------------------------------------------------------------------------
-- 4. Tampilan siap pakai
-- ---------------------------------------------------------------------------
create or replace view public.career_salary_band_view
with (security_invoker = true) as
select b.career_id,
       l.code       as level_code,
       l.name_id    as tingkat,
       l.exp_label  as pengalaman,
       l.sort_order,
       b.salary_min,
       b.salary_max
from public.career_salary_bands b
join public.salary_levels l on l.code = b.level_code;

-- ---------------------------------------------------------------------------
-- 5. Penjaga
-- ---------------------------------------------------------------------------
do $$
declare v_n int; v_naik int; v_kosong int;
begin
  select count(*) into v_kosong
  from public.careers c
  join public.career_market m on m.career_id = c.id
  where c.is_active and m.salary_min is not null
    and not exists (select 1 from public.career_salary_bands b
                    where b.career_id = c.id);
  if v_kosong > 0 then
    raise exception '0027: % profesi punya gaji tapi tidak punya pita senioritas', v_kosong;
  end if;

  -- pita harus naik: junior.max <= mid.max <= senior.max
  select count(*) into v_naik from (
    select career_id
    from public.career_salary_bands b
    join public.salary_levels l on l.code = b.level_code
    group by career_id
    having max(case when l.code='JUNIOR' then b.salary_max end)
           > min(case when l.code='MID'    then b.salary_max end)
        or max(case when l.code='MID'    then b.salary_max end)
           > min(case when l.code='SENIOR' then b.salary_max end)
  ) x;
  if v_naik > 0 then
    raise exception '0027: % profesi punya pita gaji yang tidak menaik', v_naik;
  end if;

  select count(*) into v_n from public.career_market where ai_resilience is null;
  if v_n > 0 then
    raise exception '0027: % profesi tanpa skor ketahanan AI', v_n;
  end if;

  raise notice '0027: % pita gaji; ketahanan AI min % maks % median %',
    (select count(*) from public.career_salary_bands),
    (select min(ai_resilience) from public.career_market),
    (select max(ai_resilience) from public.career_market),
    (select percentile_disc(0.5) within group (order by ai_resilience)
       from public.career_market);
end $$;

