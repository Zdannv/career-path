-- ---------------------------------------------------------------------------
-- Menutup lubang 0010: profesi yang sub-industrinya bernaung di industri baru
-- kini punya tautan industri juga. Ditandai 'turunan_subindustri' supaya bisa
-- dibedakan dari 636 tautan hasil kurasi manual di 0003.
-- ---------------------------------------------------------------------------
insert into public.career_industries (career_id, industry_code, source, is_verified)
select distinct csi.career_id, si.industry_code, 'turunan_subindustri', false
from public.career_sub_industries csi
join public.sub_industries si on si.code = csi.sub_industry_code
on conflict (career_id, industry_code) do nothing;

do $$
declare n int;
begin
  select count(*) into n from public.careers c
  where c.is_active and not exists (
    select 1 from public.career_sub_industries x where x.career_id = c.id and x.is_primary);
  if n > 0 then raise exception '% profesi aktif tidak punya sub-industri utama', n; end if;

  select count(*) into n from public.industries i
  where i.is_active and not exists (select 1 from public.sub_industries s where s.industry_code = i.code);
  if n > 0 then raise exception '% industri aktif tidak punya sub-industri', n; end if;
end $$;

alter table public.sub_industries        enable row level security;
alter table public.career_sub_industries enable row level security;
do $$
declare t text;
begin
  foreach t in array array['sub_industries','career_sub_industries'] loop
    execute format('drop policy if exists %I_read_all on public.%I', t, t);
    execute format('create policy %I_read_all on public.%I for select to anon, authenticated using (true)', t, t);
  end loop;
end $$;

