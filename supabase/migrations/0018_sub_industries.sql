-- ============================================================================
-- 0018_sub_industries.sql
--
-- Sub-industri per profesi — chip yang muncul di pojok kiri atas tiap kartu
-- profesi di layar Explore.
--
-- Alasannya ditulis sendiri oleh tim desain: "sub-industri lebih membantu user
-- memahami konteks profesi dibanding group industri yang terlalu generik,
-- karena 1 profesi bisa digunakan lebih dari 1 bidang industri." Memang begitu:
-- "Healthcare & Life Sciences" tidak memberi tahu apa pun, sedangkan "Ritel
-- Farmasi" dan "Farmasi Steril" langsung menempatkan profesinya.
--
-- Kosakatanya diambil dari kolom sub_industries di tabel industries — daftar
-- yang tim desain tulis sendiri di sheet Mapping (Industri) — diterjemahkan ke
-- bahasa Indonesia dan dipecah jadi baris, ditambah beberapa yang muncul di
-- mockup tapi belum ada di sheet.
--
-- Pemetaan profesi memakai aturan kata kunci atas nama profesi, dengan rumpun
-- SOC sebagai jaring pengaman. Semuanya bertanda is_verified = false: masuk
-- akal, belum ditinjau manusia.
--
-- Sebagai efek samping, file ini menutup lubang yang tercatat di 0010: 16
-- industri baru yang belum punya satu pun tautan profesi kini terisi, lewat
-- sub-industri yang bernaung di bawahnya.
--
-- Jalankan setelah 0017. Aman diulang.
-- ============================================================================

begin;

create table if not exists public.sub_industries (
  code          text primary key,
  industry_code text not null references public.industries(code) on delete cascade,
  name_id       text not null,
  display_order smallint not null default 99
);

create table if not exists public.career_sub_industries (
  career_id         integer not null references public.careers(id) on delete cascade,
  sub_industry_code text    not null references public.sub_industries(code) on delete cascade,
  is_primary        boolean not null default false,
  display_order     smallint not null default 99,
  source            text    not null default 'aturan_kata_kunci',
  is_verified       boolean not null default false,
  primary key (career_id, sub_industry_code)
);
comment on column public.career_sub_industries.is_primary is
  'Sub-industri yang ditampilkan di chip kartu. Sisanya diringkas jadi penanda "(+N)".';

