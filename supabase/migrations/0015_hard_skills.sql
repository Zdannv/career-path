insert into public.career_hard_skills (career_id, hard_skill_code, display_order, source)
select c.id, x.hard_skill_code, min(x.urutan), min(x.src)
from public.careers c
join _soc_hs x
  on (length(x.soc_prefix) = 2  and left(c.soc_code, 2) = x.soc_prefix)
  or (length(x.soc_prefix) > 2  and c.soc_code = x.soc_prefix)
where c.is_active
group by c.id, x.hard_skill_code
on conflict (career_id, hard_skill_code) do update set
  display_order = excluded.display_order, source = excluded.source;

-- Tiga kemampuan dengan urutan terkecil jadi inti.
update public.career_hard_skills set is_core = false;
update public.career_hard_skills chs set is_core = true
from (
  select career_id, hard_skill_code,
         row_number() over (partition by career_id order by display_order, hard_skill_code) as rn
  from public.career_hard_skills
) r
where r.career_id = chs.career_id and r.hard_skill_code = chs.hard_skill_code and r.rn <= 3;

do $$
declare n int;
begin
  select count(*) into n from public.careers c
  where c.is_active and not exists (select 1 from public.career_hard_skills x where x.career_id = c.id);
  if n > 0 then raise exception '% profesi aktif tidak punya hard skill', n; end if;

  select count(*) into n from public.careers c
  where c.is_active and (select count(*) from public.career_hard_skills x where x.career_id = c.id and x.is_core) < 3;
  if n > 0 then raise exception '% profesi aktif punya kurang dari 3 hard skill inti', n; end if;
end $$;

