-- ============================================================================
-- 0015_hard_skills.sql
--
-- Katalog hard skill yang bisa dipakai ulang lintas profesi.
--
-- Latar belakangnya keluhan Nico: roadmap menampilkan lima baris terpisah
-- "Pelajari Microsoft Outlook / Word / Office software / Excel" — daftar alat
-- mentah O*NET, tanpa kedalaman dan tanpa arti bagi pengguna. Di sini 196 alat
-- itu dilebur jadi 42 hard skill yang layak jadi quest, lalu ditambah 75
-- kemampuan domain supaya profesi lapangan yang tidak memakai software apa pun
-- tetap punya hard skill yang masuk akal.
--
-- Hard skill sengaja berdiri sebagai entitas tersendiri, bukan kolom di
-- careers: satu "Spreadsheet & Pengolahan Data" dipakai 85 profesi, dan satu
-- quest yang sama bisa melayani semuanya. Itu maksud [context_hardskill].
--
-- Tabel `skills` lama (113 entri, hampir semuanya bidang IT) tidak disentuh.
-- Ia tidak dipakai roadmap; penggantinya adalah tabel di file ini.
--
-- Jalankan setelah 0014. Aman diulang.
-- ============================================================================

begin;

create table if not exists public.hard_skill_domains (
  code    text primary key,
  name_id text not null
);

create table if not exists public.hard_skills (
  code        text primary key,
  name_id     text not null,
  domain_code text not null references public.hard_skill_domains(code),
  source      text not null default 'alat_onet',
  created_at  timestamptz not null default now()
);
comment on column public.hard_skills.source is
  'alat_onet = leburan daftar Tools & Technology O*NET. domain_soc = kemampuan domain yang disusun per rumpun SOC, bukan dari O*NET.';

-- Jejak balik ke nama alat aslinya. Tanpa ini tidak ada cara memeriksa apakah
-- peleburan 196 alat jadi 42 kemampuan sudah benar.
create table if not exists public.hard_skill_tools (
  hard_skill_code text not null references public.hard_skills(code) on delete cascade,
  tool_name       text not null,
  primary key (hard_skill_code, tool_name)
);

create table if not exists public.career_hard_skills (
  career_id       integer not null references public.careers(id) on delete cascade,
  hard_skill_code text    not null references public.hard_skills(code) on delete cascade,
  is_core         boolean not null default false,
  display_order   smallint not null default 99,
  source          text    not null default 'domain_soc',
  primary key (career_id, hard_skill_code)
);
comment on column public.career_hard_skills.is_core is
  'Ditandai true untuk kemampuan yang dijadikan quest wajib di tahap FONDASI. Sisanya muncul sebagai quest lanjutan.';

